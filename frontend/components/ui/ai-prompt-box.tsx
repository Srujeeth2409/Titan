// Main PromptInputBox Component
export interface PromptInputBoxProps {
  onSend?: (message: string, files?: File[]) => void;
  isLoading?: boolean;
  placeholder?: string;
  className?: string;
  value?: string;
  onValueChange?: (val: string) => void;
  // Workspace integration options
  model?: string;
  models?: string[];
  effort?: string;
  efforts?: string[];
  onEffortChange?: (effort: string) => void;
  collection?: string;
  collections?: string[];
  onCollectionChange?: (col: string) => void;
}

export const PromptInputBox = React.forwardRef((props: PromptInputBoxProps, ref: React.Ref<HTMLDivElement>) => {
  const {
    onSend = () => {},
    isLoading = false,
    placeholder = "Ask questions across enterprise documents…",
    className,
    value: controlledValue,
    onValueChange: controlledOnValueChange,
    model = "Ollama (Local 2.2B)",
    effort = "Medium",
    efforts = ["Low", "Medium", "Max Effort"],
    onEffortChange,
    collection = "default",
    collections = ["default"],
    onCollectionChange,
  } = props;

  const [internalInput, setInternalInput] = React.useState("");
  const input = controlledValue !== undefined ? controlledValue : internalInput;
  const setInput = controlledOnValueChange || setInternalInput;

  const [files, setFiles] = React.useState<File[]>([]);
  const [filePreviews, setFilePreviews] = React.useState<{ [key: string]: string }>({});
  const [selectedImage, setSelectedImage] = React.useState<string | null>(null);
  const [isRecording, setIsRecording] = React.useState(false);
  const [showSearch, setShowSearch] = React.useState(false);
  const [showThink, setShowThink] = React.useState(effort === "Max Effort");
  const [showCanvas, setShowCanvas] = React.useState(false);
  const uploadInputRef = React.useRef<HTMLInputElement>(null);
  const promptBoxRef = React.useRef<HTMLDivElement>(null);

  const handleToggleChange = (mode: string) => {
    if (mode === "search") {
      setShowSearch((prev) => !prev);
      setShowThink(false);
    } else if (mode === "think") {
      const nextThink = !showThink;
      setShowThink(nextThink);
      setShowSearch(false);
      if (onEffortChange) {
        onEffortChange(nextThink ? "Max Effort" : "Medium");
      }
    }
  };

  const handleCanvasToggle = () => setShowCanvas((prev) => !prev);

  const cycleEffort = () => {
    if (!onEffortChange) return;
    const currentIdx = efforts.indexOf(effort);
    const nextIdx = (currentIdx + 1) % efforts.length;
    const nextEffort = efforts[nextIdx];
    onEffortChange(nextEffort);
    setShowThink(nextEffort === "Max Effort");
  };

  const isImageFile = (file: File) => file.type.startsWith("image/");

  const processFile = (file: File) => {
    if (!isImageFile(file)) {
      console.log("Only image files are allowed for image preview");
      return;
    }
    if (file.size > 10 * 1024 * 1024) {
      console.log("File too large (max 10MB)");
      return;
    }
    setFiles([file]);
    const reader = new FileReader();
    reader.onload = (e) => setFilePreviews({ [file.name]: e.target?.result as string });
    reader.readAsDataURL(file);
  };

  const handleDragOver = React.useCallback((e: React.DragEvent) => {
    e.preventDefault();
    e.stopPropagation();
  }, []);

  const handleDragLeave = React.useCallback((e: React.DragEvent) => {
    e.preventDefault();
    e.stopPropagation();
  }, []);

  const handleDrop = React.useCallback((e: React.DragEvent) => {
    e.preventDefault();
    e.stopPropagation();
    const droppedFiles = Array.from(e.dataTransfer.files);
    const imageFiles = droppedFiles.filter((file) => isImageFile(file));
    if (imageFiles.length > 0) processFile(imageFiles[0]);
  }, []);

  const handleRemoveFile = (index: number) => {
    const fileToRemove = files[index];
    if (fileToRemove && filePreviews[fileToRemove.name]) setFilePreviews({});
    setFiles([]);
  };

  const openImageModal = (imageUrl: string) => setSelectedImage(imageUrl);

  const handlePaste = React.useCallback((e: ClipboardEvent) => {
    const items = e.clipboardData?.items;
    if (!items) return;
    for (let i = 0; i < items.length; i++) {
      if (items[i].type.indexOf("image") !== -1) {
        const file = items[i].getAsFile();
        if (file) {
          e.preventDefault();
          processFile(file);
          break;
        }
      }
    }
  }, []);

  React.useEffect(() => {
    document.addEventListener("paste", handlePaste);
    return () => document.removeEventListener("paste", handlePaste);
  }, [handlePaste]);

  const handleSubmit = () => {
    if (input.trim() || files.length > 0) {
      onSend(input.trim(), files);
      setInput("");
      setFiles([]);
      setFilePreviews({});
    }
  };

  const handleStartRecording = () => {
    // Web Speech API
    if (typeof window !== "undefined" && "webkitSpeechRecognition" in window) {
      try {
        const SpeechRec = (window as any).webkitSpeechRecognition;
        const rec = new SpeechRec();
        rec.continuous = false;
        rec.interimResults = false;
        rec.lang = "en-US";
        rec.onresult = (ev: any) => {
          const transcript = ev.results[0][0].transcript;
          setInput(input ? `${input} ${transcript}` : transcript);
          setIsRecording(false);
        };
        rec.onerror = () => setIsRecording(false);
        rec.onend = () => setIsRecording(false);
        rec.start();
      } catch {
        setIsRecording(false);
      }
    }
  };

  const handleStopRecording = (duration: number) => {
    setIsRecording(false);
  };

  const hasContent = input.trim() !== "" || files.length > 0;

  return (
    <>
      <PromptInput
        value={input}
        onValueChange={setInput}
        isLoading={isLoading}
        onSubmit={handleSubmit}
        className={cn(
          "w-full bg-white/95 border border-slate-200/90 shadow-[0_12px_40px_rgba(0,0,0,0.06)] rounded-3xl transition-all duration-300 ease-in-out",
          isRecording && "border-red-500/70 ring-2 ring-red-100",
          className
        )}
        disabled={isLoading || isRecording}
        ref={ref || promptBoxRef}
        onDragOver={handleDragOver}
        onDragLeave={handleDragLeave}
        onDrop={handleDrop}
      >
        {files.length > 0 && !isRecording && (
          <div className="flex flex-wrap gap-2 p-0 pb-1 transition-all duration-300">
            {files.map((file, index) => (
              <div key={index} className="relative group">
                {file.type.startsWith("image/") && filePreviews[file.name] && (
                  <div
                    className="w-16 h-16 rounded-xl overflow-hidden cursor-pointer transition-all duration-300 border border-slate-200 shadow-sm"
                    onClick={() => openImageModal(filePreviews[file.name])}
                  >
                    {/* eslint-disable-next-line @next/next/no-img-element */}
                    <img
                      src={filePreviews[file.name]}
                      alt={file.name}
                      className="h-full w-full object-cover"
                    />
                    <button
                      onClick={(e) => {
                        e.stopPropagation();
                        handleRemoveFile(index);
                      }}
                      className="absolute top-1 right-1 rounded-full bg-black/70 p-0.5 opacity-100 transition-opacity"
                    >
                      <X className="h-3 w-3 text-white" />
                    </button>
                  </div>
                )}
              </div>
            ))}
          </div>
        )}

        <div
          className={cn(
            "transition-all duration-300",
            isRecording ? "h-0 overflow-hidden opacity-0" : "opacity-100"
          )}
        >
          <PromptInputTextarea
            placeholder={
              showSearch
                ? "Search across company records and web…"
                : showThink
                ? "Deep reasoning across all document chunks…"
                : showCanvas
                ? "Synthesize answer into document format…"
                : placeholder
            }
            className="text-base text-slate-800 placeholder:text-slate-400 font-normal"
          />
        </div>

        {isRecording && (
          <VoiceRecorder
            isRecording={isRecording}
            onStartRecording={handleStartRecording}
            onStopRecording={handleStopRecording}
          />
        )}

        <PromptInputActions className="flex items-center justify-between gap-2 p-0 pt-2 border-t border-slate-100 mt-1">
          <div
            className={cn(
              "flex items-center gap-1.5 flex-wrap transition-opacity duration-300",
              isRecording ? "opacity-0 invisible h-0" : "opacity-100 visible"
            )}
          >
            {/* Model Pill: Strictly Ollama Local 2.2B */}
            <div
              className="flex items-center gap-1.5 px-2.5 py-1 rounded-full bg-slate-100/90 text-slate-700 text-xs font-semibold border border-slate-200/70"
              title="Pinned to Local Ollama 2.2B"
            >
              <span className="w-2 h-2 rounded-full bg-emerald-500 shadow-[0_0_6px_rgba(16,185,129,0.5)]" />
              <span>{model}</span>
            </div>

            {/* Collection / Target Pill */}
            {collections && collections.length > 0 && (
              <div className="relative group">
                <select
                  value={collection}
                  onChange={(e) => onCollectionChange?.(e.target.value)}
                  className="appearance-none bg-slate-100/90 hover:bg-slate-200/90 text-slate-700 text-xs font-medium pl-2.5 pr-6 py-1 rounded-full border border-slate-200/70 outline-none cursor-pointer transition-colors"
                >
                  {collections.map((col) => (
                    <option key={col} value={col}>
                      📁 {col}
                    </option>
                  ))}
                </select>
                <div className="pointer-events-none absolute right-2 top-1/2 -translate-y-1/2 text-slate-400 text-[10px]">
                  ▼
                </div>
              </div>
            )}

            {/* Effort Pill: Cycles Low -> Medium -> Max Effort */}
            <button
              type="button"
              onClick={cycleEffort}
              className={cn(
                "rounded-full transition-all flex items-center gap-1 px-2.5 py-1 text-xs font-semibold border h-7 cursor-pointer",
                effort === "Max Effort"
                  ? "bg-purple-50 text-purple-700 border-purple-200"
                  : effort === "Low"
                  ? "bg-emerald-50 text-emerald-700 border-emerald-200"
                  : "bg-indigo-50 text-indigo-700 border-indigo-200"
              )}
              title="Click to change RAG Effort level"
            >
              <span>{effort === "Max Effort" ? "🧠" : effort === "Low" ? "⚡" : "📊"}</span>
              <span>{effort}</span>
            </button>

            <CustomDivider />

            {/* Image upload */}
            <PromptInputAction tooltip="Attach image for visual context">
              <button
                type="button"
                onClick={() => uploadInputRef.current?.click()}
                className="flex h-7 w-7 text-slate-400 hover:text-slate-600 cursor-pointer items-center justify-center rounded-full transition-colors hover:bg-slate-100"
                disabled={isRecording}
              >
                <Paperclip className="h-4 w-4" />
                <input
                  ref={uploadInputRef}
                  type="file"
                  className="hidden"
                  onChange={(e) => {
                    if (e.target.files && e.target.files.length > 0) processFile(e.target.files[0]);
                    if (e.target) e.target.value = "";
                  }}
                  accept="image/*"
                />
              </button>
            </PromptInputAction>

            {/* Deep Reasoning toggle */}
            <button
              type="button"
              onClick={() => handleToggleChange("think")}
              className={cn(
                "rounded-full transition-all flex items-center gap-1 px-2 py-0.5 border h-7 text-xs font-medium cursor-pointer",
                showThink
                  ? "bg-purple-100 border-purple-300 text-purple-700"
                  : "bg-transparent border-transparent text-slate-400 hover:text-slate-700 hover:bg-slate-100"
              )}
              title="Toggle Deep Reasoning"
            >
              <BrainCog className="w-3.5 h-3.5" />
              <span>Think</span>
            </button>
          </div>

          {/* Action Button: Send / Stop / Mic */}
          <PromptInputAction
            tooltip={
              isLoading
                ? "Stop generation"
                : isRecording
                ? "Stop recording"
                : hasContent
                ? "Send message (Enter)"
                : "Voice input"
            }
          >
            <Button
              variant="default"
              size="icon"
              className={cn(
                "h-8 w-8 rounded-full transition-all duration-200 shadow-sm cursor-pointer",
                isRecording
                  ? "bg-red-500 hover:bg-red-600 text-white"
                  : hasContent
                  ? "bg-indigo-600 hover:bg-indigo-700 text-white"
                  : "bg-slate-100 hover:bg-slate-200 text-slate-500 hover:text-slate-800"
              )}
              onClick={() => {
                if (isRecording) setIsRecording(false);
                else if (hasContent) handleSubmit();
                else setIsRecording(true);
              }}
              disabled={isLoading && !hasContent}
            >
              {isLoading ? (
                <Square className="h-3.5 w-3.5 fill-white animate-pulse" />
              ) : isRecording ? (
                <StopCircle className="h-4 w-4 text-white" />
              ) : hasContent ? (
                <ArrowUp className="h-4 w-4 text-white" />
              ) : (
                <Mic className="h-4 w-4" />
              )}
            </Button>
          </PromptInputAction>
        </PromptInputActions>
      </PromptInput>

      <ImageViewDialog imageUrl={selectedImage} onClose={() => setSelectedImage(null)} />
    </>
  );
});
PromptInputBox.displayName = "PromptInputBox";
